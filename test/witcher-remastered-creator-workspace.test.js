'use strict';
const test=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const read=p=>fs.readFileSync(path.join(__dirname,'..',p),'utf8');
const {equivalent,searchNames,editorialGame}=require('../modules/swapp-news/game-identity');
const metadata=require('../modules/swapp-news/content-metadata');
const curation=require('../assets/swapp-live-curation');
const browser=require('../assets/swapp-game-identity');

test('Witcher 3 Remastered resolves the verified Twitch category, without merging the original game',()=>{
 for(const alias of ['Witcher 3 Remastered','The Witcher 3 Remastered','The Witcher III Remastered']){
  assert.equal(equivalent(alias,'The Witcher 3: Wild Hunt Remastered'),true,alias);
  assert.equal(equivalent(alias,'The Witcher 3: Wild Hunt'),false,alias);
  assert.equal(browser.sameGame(alias,'The Witcher 3: Wild Hunt Remastered'),true);
  assert.equal(browser.sameGame(alias,'The Witcher 3: Wild Hunt'),false);
 }
 assert.ok(searchNames('Witcher 3 Remastered').includes('The Witcher 3: Wild Hunt Remastered'));
 assert.equal(equivalent('The Witcher 3: Wild Hunt','The Witcher 3'),true);
});
test('article headlines repair legacy Witcher game metadata, but do not reclassify unrelated games',()=>{
 const legacy={title:'The Witcher 3 Remastered : que vaut cette édition ?',game:'The Witcher 3'};
 assert.equal(editorialGame(legacy),'The Witcher 3: Wild Hunt Remastered');
 assert.equal(browser.editorialGame(legacy),'The Witcher 3: Wild Hunt Remastered');
 assert.equal(editorialGame({title:'The Witcher 3 Remastered',game:'Cyberpunk 2077'}),'Cyberpunk 2077');
 assert.equal(editorialGame({title:'The Witcher 3 : notre avis',game:'The Witcher 3'}),'The Witcher 3');
 assert.deepEqual(metadata.detectGames('The Witcher 3 Remastered reçoit une mise à jour',1),['The Witcher 3: Wild Hunt Remastered']);
 assert.equal(metadata.recommend(legacy).primaryGame,'The Witcher 3: Wild Hunt Remastered');
});
test('actual streams on the Remastered category match existing published news without inventing a live',()=>{
 const published={slug:'witcher-3-remastered-analyse',title:'The Witcher 3 Remastered : nouvelle version',game:'The Witcher 3'};
 const match=curation.matchLiveToArticle({game_name:'The Witcher 3: Wild Hunt Remastered'},[published]);
 assert.equal(match?.slug,published.slug);
 assert.equal(curation.matchLiveToArticle({game_name:'The Witcher 3: Wild Hunt'},[published]),null);
 assert.equal(curation.featuredGames([published])[0],'The Witcher 3: Wild Hunt Remastered');
 assert.equal(curation.matchLiveToArticle({game_name:'Hades'},[{slug:'hades-ii-essai',game:'Hades II',title:'Hades II essai'}]),null);
});
